#!/usr/bin/env python3
"""Bake the globe's terrain data into earth_data.js (window.EARTH, two PNG data URIs).

    python3 tools/earth_data.py <etopo.csv> <bluemarble.jpg>

etopo.csv: NOAA ETOPO1 via ERDDAP at 1/6 degree,
  https://coastwatch.pfeg.noaa.gov/erddap/griddap/etopo180.csv0?altitude[(-90):10:(90)][(-180):10:(180)]
bluemarble.jpg: NASA Blue Marble (public domain), Wikimedia "Whole world - land and oceans", 3840 px wide.

land.png  720x360, row 0 = 90N, col 0 = 180W.  RGB = mean Blue Marble colour of the cell; the colour channels are
          left at 0 for sea.  A separate grey band is not used: elevation goes in elev.png.
terra.png 1440x720 RGB.  R = land height of the half-degree cell it sits in, sqrt-coded, 255 = 6500 m (the cell's 80th
          percentile, so ranges read as ranges); G = sea depth at 1/4 degree, sqrt-coded, 255 = 8000 m; B = 0.
"""
import base64, io, sys
from pathlib import Path
import numpy as np
from PIL import Image

csv, bm = sys.argv[1], sys.argv[2]
z = np.loadtxt(csv, delimiter=",", usecols=2, dtype=np.float32)
nlat, nlon = 1081, 2161
z = z.reshape(nlat, nlon)[::-1, :-1][:-1]        # north first, drop the duplicate 180E column -> 1080 x 2160
# half-degree land height: 3x3 samples per cell, 80th percentile of the land samples
c = z.reshape(360, 3, 720, 3).transpose(0, 2, 1, 3).reshape(360, 720, 9)
land = np.where(c > 0, c, np.nan)
h = np.nan_to_num(np.nanpercentile(land, 80, axis=2), nan=0.0) if np.isfinite(land).any() else np.zeros((360, 720))
# quarter-degree sea depth (mean of the water samples), upsampled from 1/6: take a 2160->1440 resize
dep = np.clip(-z, 0, None)
depth = np.asarray(Image.fromarray(dep).resize((1440, 720), Image.BILINEAR))
hcode = np.sqrt(np.clip(h, 0, 6500) / 6500) * 255
hbig = np.repeat(np.repeat(hcode, 2, 0), 2, 1)
terra = np.dstack([hbig, np.sqrt(np.clip(depth, 0, 8000) / 8000) * 255, np.zeros_like(hbig)]).round().astype(np.uint8)
# land colour: Blue Marble averaged per half-degree cell
img = np.asarray(Image.open(bm).convert("RGB").resize((720 * 4, 360 * 4), Image.LANCZOS), dtype=np.float32)
col = img.reshape(360, 4, 720, 4, 3).mean(axis=(1, 3))
col[h <= 0] = 0
def uri(a):
    b = io.BytesIO(); Image.fromarray(a).save(b, "PNG", optimize=True); return "data:image/png;base64," + base64.b64encode(b.getvalue()).decode()
out = Path(__file__).resolve().parent.parent / "earth_data.js"
out.write_text("/* Generated by tools/earth_data.py from NOAA ETOPO1 (terrain, bathymetry) and NASA Blue Marble (land colour). */\n"
               f'window.EARTH={{land:"{uri(col.round().astype(np.uint8))}",terra:"{uri(terra)}"}};\n')
print(out, f"{out.stat().st_size/1e3:.0f} kB", "max land m", float(h.max()), "max depth m", float(dep.max()))
